def read_mask01(p: Path) -> np.ndarray:
    """
    讀灰階 mask，轉成 0/1
    """
    m = cv2.imread(str(p), cv2.IMREAD_GRAYSCALE)
    if m is None:
        raise FileNotFoundError(p)
    return (m > 127).astype(np.uint8)

def close_mask(mask01: np.ndarray, ksize: int = 9, iterations: int = 1) -> np.ndarray:
    """
    閉運算：
    先膨脹再侵蝕，用來關閉小缺口、補小裂縫
    """
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (ksize, ksize))
    out = cv2.morphologyEx(mask01.astype(np.uint8), cv2.MORPH_CLOSE, kernel, iterations=iterations)
    return (out > 0).astype(np.uint8)

def fill_holes(mask01: np.ndarray) -> np.ndarray:
    """
    填滿內部孔洞
    """
    filled = binary_fill_holes(mask01 > 0)
    return filled.astype(np.uint8)

def close_and_fill(mask01: np.ndarray, ksize: int = 9, iterations: int = 1) -> np.ndarray:
    """
    先關閉缺口，再 fill hole
    """
    closed = close_mask(mask01, ksize=ksize, iterations=iterations)
    filled = fill_holes(closed)
    return filled.astype(np.uint8)

def keep_largest_component(mask01: np.ndarray) -> np.ndarray:
    """
    只保留最大連通區
    適合 embryo_outer，避免小雜點被一起算進面積
    """
    mask01 = (mask01 > 0).astype(np.uint8)
    num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(mask01, connectivity=8)

    if num_labels <= 1:
        return mask01.copy()

    areas = stats[1:, cv2.CC_STAT_AREA]   # 跳過背景 0
    largest_idx = 1 + int(np.argmax(areas))

    out = np.zeros_like(mask01, dtype=np.uint8)
    out[labels == largest_idx] = 1
    return out

def mask_area(mask01: np.ndarray) -> int:
    """
    計算 mask 面積（像素數）
    """
    return int((mask01 > 0).sum())

def contour_from_mask01(mask01: np.ndarray):
    """
    從 mask 取最大外輪廓，用來畫 overlay
    """
    m = (mask01 * 255).astype(np.uint8)
    cnts, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    if not cnts:
        return None
    cnt = max(cnts, key=cv2.contourArea)
    return cnt.reshape(-1, 2)

def draw_area_overlay(zp01: np.ndarray, embryo01: np.ndarray) -> np.ndarray:
    """
    畫面積比例 QC 疊圖：
      - zp_outer：綠線
      - embryo_outer：紅線
    背景用深灰方便看
    """
    h, w = zp01.shape[:2]
    vis = np.zeros((h, w, 3), dtype=np.uint8)
    vis[:] = 30  # 深灰背景

    cnt_zp = contour_from_mask01(zp01)
    cnt_em = contour_from_mask01(embryo01)

    if cnt_zp is not None:
        cv2.polylines(vis, [cnt_zp.astype(np.int32)], True, (0, 255, 0), 2)   # 綠
    if cnt_em is not None:
        cv2.polylines(vis, [cnt_em.astype(np.int32)], True, (0, 0, 255), 2)   # 紅

    return vis

def compute_area_ratio_metrics(zp_outer01: np.ndarray, embryo_outer01: np.ndarray,
                               zp_close_ksize: int = 9, embryo_close_ksize: int = 9):
    """
    核心量測函數：
      1) zp_outer：關閉缺口 + fill hole
      2) embryo_outer：關閉缺口 + fill hole + 保留最大連通區
      3) 算面積與比例
    """
    # ZP outer：閉運算 + 補洞
    zp_clean = close_and_fill(zp_outer01, ksize=zp_close_ksize, iterations=1)

    # Embryo outer：閉運算 + 補洞 + 主體保留
    embryo_clean = close_and_fill(embryo_outer01, ksize=embryo_close_ksize, iterations=1)
    embryo_main = keep_largest_component(embryo_clean)

    # 面積
    zp_area = mask_area(zp_clean)
    embryo_area = mask_area(embryo_main)

    # 比例
    ratio = embryo_area / zp_area if zp_area > 0 else np.nan
    remain_area = zp_area - embryo_area if zp_area > 0 else np.nan

    return {
        "zp_clean": zp_clean,
        "embryo_main": embryo_main,
        "zp_outer_area": zp_area,
        "embryo_outer_area": embryo_area,
        "embryo_to_zp_ratio": ratio,
        "zp_minus_embryo_area": remain_area,
    }

