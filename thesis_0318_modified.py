def polygon_area(points):
    pts = np.asarray(points, dtype=np.float32)
    if len(pts) < 3:
        return 0.0
    x = pts[:, 0]
    y = pts[:, 1]
    return 0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1)))

def shape_to_mask(img_h, img_w, points):
    img = Image.new("L", (img_w, img_h), 0)
    draw = ImageDraw.Draw(img)
    xy = [tuple(map(float, p)) for p in points]
    draw.polygon(xy, outline=1, fill=1)
    return np.array(img, dtype=np.uint8)

def pick_largest_shape_by_candidates(shapes, label_candidates):
    cand = []
    label_candidates = set(label_candidates)
    for sh in shapes:
        if sh.get("label") in label_candidates and len(sh.get("points", [])) >= 3:
            cand.append(sh)

    if len(cand) == 0:
        return None

    areas = [polygon_area(sh["points"]) for sh in cand]
    idx = int(np.argmax(areas))
    return cand[idx]

